#!/usr/bin/env bash
# ===========================================================================
#  yt-dlp GUI - Linux installer (per-user, no root needed)
#
#  Installs a menu entry + icon so the app appears in your application
#  launcher (GNOME Activities, KDE, XFCE, ...), and a small wrapper in
#  ~/.local/bin so you can also run `yt-dlp-gui` from a terminal.
#
#  Usage, from the repository root:
#      ./launchers/linux/install-desktop-entry.sh            # install
#      ./launchers/linux/install-desktop-entry.sh --uninstall
# ===========================================================================
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"

APP_ID="yt-dlp-gui"
NAME="yt-dlp GUI"
DESKTOP_NAME="$APP_ID.desktop"

DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
BIN_HOME="$HOME/.local/bin"
APPS_DIR="$DATA_HOME/applications"
ICON_DIR="$DATA_HOME/icons/hicolor/256x256/apps"
WRAPPER="$BIN_HOME/$APP_ID"

[ -f "$ROOT/yt_dlp_gui.py" ] || { echo "Run this from inside the yt-dlp-gui repo." >&2; exit 1; }

# ---- uninstall ------------------------------------------------------------
if [ "${1:-}" = "--uninstall" ]; then
  rm -f "$APPS_DIR/$DESKTOP_NAME" "$ICON_DIR/$APP_ID.png" "$WRAPPER"
  command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true
  command -v gtk-update-icon-cache >/dev/null 2>&1 && gtk-update-icon-cache -f -t "$DATA_HOME/icons/hicolor" >/dev/null 2>&1 || true
  echo "Removed $NAME from the application menu."
  exit 0
fi

# ---- sanity: Python 3 with Tkinter ---------------------------------------
PY=""
for c in python3 python; do
  if command -v "$c" >/dev/null 2>&1 && "$c" -c "import tkinter" >/dev/null 2>&1; then
    PY="$(command -v "$c")"; break
  fi
done
if [ -z "$PY" ]; then
  echo "No Python 3 with Tkinter was found. Install it first:" >&2
  echo "    Debian/Ubuntu : sudo apt install python3 python3-tk" >&2
  echo "    Fedora        : sudo dnf install python3 python3-tkinter" >&2
  echo "    Arch          : sudo pacman -S python tk" >&2
  echo "    openSUSE      : sudo zypper install python3 python3-tk" >&2
  exit 1
fi
echo "Using $PY"

# ---- icon ----------------------------------------------------------------
mkdir -p "$APPS_DIR" "$ICON_DIR" "$BIN_HOME"
if [ ! -f "$ROOT/build/icon.png" ]; then
  echo "Generating the icon..."
  ( cd "$ROOT" && "$PY" build/make_icon.py >/dev/null )
fi
cp "$ROOT/build/icon.png" "$ICON_DIR/$APP_ID.png"
echo "icon     -> $ICON_DIR/$APP_ID.png"

# ---- terminal wrapper ----------------------------------------------------
{
  echo '#!/usr/bin/env bash'
  echo "# Generated by launchers/linux/install-desktop-entry.sh"
  echo "exec \"$ROOT/launchers/linux/yt-dlp-gui.sh\" \"\$@\""
} > "$WRAPPER"
chmod +x "$WRAPPER"
echo "command  -> $WRAPPER"

# ---- desktop entry -------------------------------------------------------
mkdir -p "$APPS_DIR"
sed -e "s|__EXEC__|$WRAPPER|g" \
    -e "s|__ICON__|$APP_ID|g" \
    "$HERE/yt-dlp-gui.desktop.in" > "$APPS_DIR/$DESKTOP_NAME"
chmod +x "$APPS_DIR/$DESKTOP_NAME"
echo "menu     -> $APPS_DIR/$DESKTOP_NAME"

# ---- refresh caches ------------------------------------------------------
command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true
command -v gtk-update-icon-cache >/dev/null 2>&1 && gtk-update-icon-cache -f -t "$DATA_HOME/icons/hicolor" >/dev/null 2>&1 || true
if command -v desktop-file-validate >/dev/null 2>&1; then
  desktop-file-validate "$APPS_DIR/$DESKTOP_NAME" || true
fi

echo
echo "Done. '$NAME' should now appear in your application menu."
case ":$PATH:" in
  *":$BIN_HOME:"*) echo "You can also run: $APP_ID" ;;
  *) echo "To run '$APP_ID' from a terminal, add ~/.local/bin to PATH." ;;
esac
